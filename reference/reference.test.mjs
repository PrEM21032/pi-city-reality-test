// Runs the shared attack cases against the reference truth core, plus
// reference-only checks for rules the attack cases do not cover. Needs no
// city snapshot. Every test here must pass: nothing is marked todo.
import { test } from "node:test";
import assert from "node:assert/strict";
import * as core from "./truth-core.mjs";
import * as imp from "./import-rows.mjs";
import { CASES, DEF_RS, SID_A, SID_B, p2Rows, refAdapter, MISSION_V18, BACK_V18_EXEC } from "../truth-tests/cases.mjs";

const R = { ...core, ...imp };
const r = refAdapter(R);
const { EvidenceLog, judge, LEVEL } = core;

for (const k of CASES) {
  test(`[${k.id}] ${k.title}`, async () => {
    assert.deepEqual(await k.ref(r, R), k.expect.ref);
  });
}

// ---- evidence log ----------------------------------------------------------
test("[R1] altering, dropping or reordering an evidence entry breaks the chain", () => {
  const log = R.importLegacy(MISSION_V18, BACK_V18_EXEC);
  const entries = log.entries();
  assert.ok(EvidenceLog.fromEntries(entries));
  const altered = entries.map((e) => ({ ...e }));
  altered[4] = { ...altered[4], event: { ...altered[4].event, status: 200, ok: true, run: "cse_01ForgedForgedForgedFo" } };
  assert.throws(() => EvidenceLog.fromEntries(altered), /chain broken/);
  assert.throws(() => EvidenceLog.fromEntries(entries.filter((_, i) => i !== 3)), /chain broken/);
  assert.throws(() => EvidenceLog.fromEntries([entries[1], entries[0], ...entries.slice(2)]), /chain broken/);
});

test("[R2] stored entries are immutable and the log has no update or delete", () => {
  const log = new EvidenceLog();
  const e = log.append({ type: "request", mission: "m", action: "verify", nonce: "abcdef", at: "2026-10-13T00:00:00Z" });
  assert.throws(() => { e.event.nonce = "zzzzzz"; }, TypeError);
  assert.equal(log.entries()[0].event.nonce, "abcdef");
  assert.equal(typeof log.delete, "undefined");
  assert.equal(typeof log.update, "undefined");
});

// ---- verification ------------------------------------------------------------
test("[R3] every requested fact is compared (the issue-body drift seen live)", () => {
  const log = R.importLegacy(MISSION_V18, BACK_V18_EXEC);
  const facts = ["number", "html_url", "title", "body"];
  const requested = "Created by PI City Reality Test. This issue exists only to verify that a mission completed inside PI City can create real external work.";
  const exec = log.events("execution")[0];
  const withBody = new EvidenceLog();
  for (const ev of log.events()) {
    if (ev.type === "execution") withBody.append({ ...ev, facts: { ...exec.facts, body: requested } });
    else if (ev.type === "verification") withBody.append({ ...ev, facts: { ...ev.facts, body: `${requested}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_` } });
    else withBody.append(ev);
  }
  const res = judge(withBody, { mission: "reality-001", requestedFacts: facts, scope: R.LEGACY_SCOPE });
  assert.equal(res.level, LEVEL.FAILED);
  assert.match(res.reason, /facts differ/);
});

test("[R4] distinct-path policy rejects a verifier on the same path as the executor", () => {
  const rows = p2Rows();
  const opts = { mission: DEF_RS.id, requestedFacts: DEF_RS.verifier.match, scope: DEF_RS.permission.scope, policy: { independence: "distinct-path" } };
  assert.equal(judge(R.importProtocol2(DEF_RS, rows.page, rows.back), opts).level, LEVEL.REPORTED);
  rows.back.verifications.veri0001.path = "github-action";
  assert.equal(judge(R.importProtocol2(DEF_RS, rows.page, rows.back), opts).level, LEVEL.REAL);
});

test("[R5] conflicting self-reported and dispatcher-reported identities are unknown", () => {
  assert.equal(r.p2Level(p2Rows({ verRun: SID_B, verFire: "cse_01ZzzzzzzzzzzzzzzzzzzzzzZ3" })), LEVEL.REPORTED);
  assert.equal(core.runIdentity({ run: SID_A, fire: SID_A }), SID_A);
  assert.equal(core.runIdentity({ run: `${SID_A} (manual)` }), null);
});

// ---- permission -------------------------------------------------------------
test("[R6] a permission recorded by an agent is not an owner grant", () => {
  const rows = p2Rows({ decidedIn: "Owner instruction in chat to Claude, recorded by Claude" });
  assert.equal(r.p2Level(rows), LEVEL.PERMISSION);
});

// ---- consistency with the city ------------------------------------------------
test("[R7] the reference's mission definition matches the pinned city snapshot", async (t) => {
  const { load } = await import("../truth-tests/extract.mjs");
  const X = load();
  if (!X) return t.skip("PI_CITY_HTML not set");
  const def = X.missionDefs.find((d) => d.id === DEF_RS.id);
  assert.equal(def.permission.scope, DEF_RS.permission.scope);
  assert.deepEqual(def.verifier.match, DEF_RS.verifier.match);
  assert.equal(def.result, DEF_RS.result);
});
